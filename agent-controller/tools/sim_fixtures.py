#!/usr/bin/env python3
"""Writes firmware/sim/fixtures/screens.jsonl: one of every screen, for `make snapshots`.

The views come from the companion app's real view builder, so the simulator (and later the
dock) is always tested against exactly what the app sends.

    python tools/sim_fixtures.py
"""

from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "software" / "companion-app"))

from companion.core.state import Approval, Screen, Session, State, Status  # noqa: E402
from companion.protocol.messages import encode, msg  # noqa: E402
from companion.view import builder  # noqa: E402

NOW = 1_795_000_000  # a fixed "now", so the pictures don't change from run to run
OUT = ROOT / "firmware" / "sim" / "fixtures" / "screens.jsonl"
DEMO = ROOT / "firmware" / "bench" / "dock_ui" / "demo_messages.h"

REPLY = (
    "The login bug is fixed.\n\n"
    "The session cookie was set without the Secure flag when the app ran behind the proxy, so "
    "browsers dropped it on the redirect back from the identity provider. I changed "
    "`cookie_settings()` to trust the X-Forwarded-Proto header and added a test that goes "
    "through the whole redirect.\n\n"
    "What changed:\n"
    "• auth/cookies.py — read the forwarded protocol\n"
    "• tests/test_login_flow.py — new end-to-end test\n"
    "• docs/deploy.md — a note about the proxy header\n\n"
    "All 212 tests pass. I did not touch the logout path; it has the same pattern and is "
    "worth a look next. “Remember me” still uses the old 30-day cookie — say if you want that "
    "shortened too."
)


def sessions() -> State:
    st = State()
    rows = [
        ("s1", "website", Status.WAITING, 40, "Bash: npm run deploy", None, None, "Claude needs your permission"),
        ("s2", "agent-controller", Status.WORKING, 135, "Edit: firmware/lib/AgentUI/src/AgentUI.cpp", 135, None, "> draw the screens"),
        ("s3", "mitzi", Status.DONE, 600, "", None, 384, REPLY),
        ("s4", "live-interpreter", Status.ERROR, 900, "", None, 12, "API error: overloaded"),
        ("s5", "wispr-faux", Status.READY, 1200, "", None, None, ""),
        ("s6", "notes", Status.IDLE, 7200, "", None, 55, "Done."),
    ]
    titles = {"s1": "Put the new pricing page live", "s2": "Draw the screens so they run on the dock too",
              "s3": "Fix the login bug behind the proxy"}  # the others have no task yet: they show the project
    for sid, name, status, ago, tool, turn_ago, worked, text in rows:
        st.sessions[sid] = Session(sid, "claude_code", cwd=f"/Users/nico/projects/{name}", name=name,
                                   title=titles.get(sid, ""), status=status,
                                   since=NOW - ago, tool=tool, text=text,
                                   turn_started=(NOW - turn_ago) if turn_ago else None, worked_s=worked)
    return st


def view(st: State) -> str:
    return encode(msg("view", **builder.build(st)))


def snap(name: str) -> str:
    return encode({"v": 1, "t": "snap", "name": name})


async def main() -> None:
    lines = ["# Generated by tools/sim_fixtures.py from the companion app's view builder. Don't edit.",
             snap("01-connecting")]

    st = sessions()
    lines += [encode(msg("welcome", proto=1, mac_ms=NOW * 1000, view=builder.build(st))),
              encode(msg("led", mode=builder.led_mode(st))), snap("02-agents")]

    st.focus.sel, st.focus.sel_id = 4, "s5"  # further down: the list scrolls
    lines += [view(st), snap("03-agents-scrolled")]

    st.focus.screen, st.focus.detail_id, st.focus.sel_id = Screen.DETAIL, "s3", "s3"
    lines += [view(st), snap("04-detail")]
    st.focus.scroll = 3
    lines += [view(st), snap("05-detail-scrolled")]

    st.focus.detail_id, st.focus.scroll = "s2", 0
    lines += [view(st), snap("06-detail-working")]

    st.focus.screen = Screen.APPROVAL
    fut = asyncio.get_running_loop().create_future()
    for i, cmd in enumerate(["npm run deploy -- --prod --confirm && git push origin main --tags", "rm -rf dist"]):
        st.approvals.append(Approval(id=f"pr-{i}", session_id="s1", tool_name="Bash", summary=cmd,
                                     tool_input={"command": cmd}, suggestions=[], future=fut))
    lines += [view(st), encode(msg("sound", name="alert")), snap("07-approval")]
    st.focus.approval_sel = 1
    lines += [view(st), snap("08-approval-second-option")]

    st.approvals.clear()
    st.focus.screen = Screen.HOME
    st.focus.sel, st.focus.sel_id = 0, "s1"
    lines += [view(st), encode(msg("toast", text="Approved for session", ms=1500)), snap("09-toast"),
              encode({"v": 1, "t": "wait", "ms": 2000})]

    st.focus.screen, st.voice = Screen.VOICE, "recording"
    lines += [view(st), snap("10-voice-recording")]

    st.sessions.clear()
    st.focus.screen, st.voice = Screen.HOME, "idle"
    lines += [view(st), snap("11-agents-empty")]

    st = sessions()
    st.sessions["s2"].title = "café — “naïve” résumé 🚀 ✓"  # what the built-in font can't show
    lines += [view(st), encode({"v": 1, "t": "link", "up": False}), snap("12-disconnected")]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(lines)} lines)")

    # The dock's demo (firmware/bench/dock_ui) steps through the same screens with no Mac attached.
    demo = [l for l in lines if not l.startswith("#") and json.loads(l)["t"] in ("welcome", "view", "toast")]
    header = ["// Demo screens for dock_ui: the simulator's fixtures (firmware/sim/fixtures/screens.jsonl).",
              "// Generated by tools/sim_fixtures.py. Don't edit.", "#pragma once", "",
              "static const char *const DEMO_MESSAGES[] = {",
              *[f'    R"json({l})json",' for l in demo], "};",
              "static const size_t DEMO_COUNT = sizeof(DEMO_MESSAGES) / sizeof(DEMO_MESSAGES[0]);", ""]
    DEMO.write_text("\n".join(header), encoding="utf-8")
    print(f"wrote {DEMO.relative_to(ROOT)} ({len(demo)} messages)")


if __name__ == "__main__":
    asyncio.run(main())
